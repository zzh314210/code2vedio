PALETTES = {
 'studio_noir': dict(bg='#101521', fg='#F4F7FF', muted='#BAC5D8', accent='#63DBE8', second='#B49AFF', panel='#1A2233', line='#303C54', good='#7EE6B4'),
 'studio_editorial': dict(bg='#F5F6F2', fg='#173B3A', muted='#526B69', accent='#087F80', second='#D35D3A', panel='#FFFFFF', line='#D7E0D9', good='#087F66'),
 'studio_sketch': dict(bg='#FBF7EE', fg='#283A44', muted='#526570', accent='#196CA5', second='#C56127', panel='#F0EADB', line='#CEC8BA', good='#28784D'),
}

def tokens(scene):
    return PALETTES.get(scene.lesson_style.get('template_id'), PALETTES['studio_noir'])

def text(scene, value, size=28, color=None, point=None):
    if scene.lesson_style.get('template_id')=='studio_sketch': value=value.replace('↔','与')
    mob=scene.scene_text(value, size, color or tokens(scene)['fg'])
    if point is not None: mob.move_to(point)
    return mob

def line(scene, a, b, color=None, width=2):
    if scene.lesson_style.get('template_id')=='studio_sketch':
        return scene.sketch_line(a,b,color or tokens(scene)['line'],width)
    return Line(a,b,stroke_color=color or tokens(scene)['line'],stroke_width=width)

def panel(scene, width, height, center):
    p=tokens(scene)
    shape=RoundedRectangle(width=width,height=height,corner_radius=.15,fill_color=p['panel'],fill_opacity=1,stroke_color=p['line'],stroke_width=1)
    shape.move_to(center)
    return shape

def chrome(scene, stage, label):
    p=tokens(scene)
    left=-6.25; right=6.25
    brand=text(scene,'折解 / 空间推理',21,p['muted'],[-5.15,3.48,0])
    section=text(scene,label,26,p['fg'],[0,3.45,0])
    counter=text(scene,f'{stage+1:02d} / 06',20,p['muted'],[5.65,3.46,0])
    top=line(scene,[left,3.02,0],[right,3.02,0],p['line'],1)
    bottom=line(scene,[left,-3.77,0],[right,-3.77,0],p['line'],2)
    progress=line(scene,[left,-3.77,0],[left+(right-left)*(stage+1)/6,-3.77,0],p['accent'],3)
    if scene.lesson_style.get('template_id')=='studio_noir':
        grid=VGroup(*[Line([x,-2.8,0],[x,2.8,0],stroke_color=p['line'],stroke_opacity=.18,stroke_width=.5) for x in np.arange(-6,6.1,.5)],*[Line([-6,y,0],[6,y,0],stroke_color=p['line'],stroke_opacity=.18,stroke_width=.5) for y in np.arange(-2.5,2.6,.5)])
        grid.set_z_index(-10);scene.add(grid)
    elif scene.lesson_style.get('template_id')=='studio_editorial':
        scene.add(Rectangle(width=.065,height=.6,stroke_width=0,fill_color=p['second'],fill_opacity=1).move_to([-6.55,3.43,0]))
    else:
        scene.add(text(scene,'看得见的解题过程',17,p['muted'],[4.8,-2.7,0]).rotate(-.035))
    scene.add(brand,section,counter,top,bottom,progress)

class CubeView(VGroup):
    def __init__(self,scene,net=EXAMPLE,scale=1.1,center=ORIGIN,fold=0,alternate=False,highlight=False):
        super().__init__()
        self._scene_ref=weakref.ref(scene);self.net=net;self.unit=scale;self.center_point=np.array(center,dtype=float)
        self.alternate=alternate;self.highlight=highlight
        self.p=tokens(scene)
        self.labels={k:text(scene,k,30).set_width(.28) for k in net}
        self.faces={k:VGroup() for k in net}
        self.add(*self.faces.values())
        self.highlight_lines=VGroup();self.add(self.highlight_lines)
        self.update_pose(fold)

    @property
    def scene(self):
        return self._scene_ref()

    def update_pose(self,fold,camera=None):
        f=frames(self.net,fold,root='B')
        camera=fold if camera is None else camera
        yaw=-np.pi/6*camera; pitch=-2*np.pi/3*camera
        projection=np.array([[np.cos(yaw),np.sin(yaw),0],[-np.sin(yaw)*np.cos(pitch),np.cos(yaw)*np.cos(pitch),np.sin(pitch)]])
        camera_normal=np.cross(projection[0],projection[1])
        offset=np.array([0,0,-.5*fold])
        def project(points):
            result=(np.asarray(points)-offset)@projection.T*self.unit
            return np.c_[result,np.zeros(len(result))]+self.center_point
        records=[]
        for name,(c,u,v) in f.items():
            # D's original material coordinates are 180 degrees from the new net frame.
            if self.alternate and name=='D':u,v=-u,-v
            normal=np.cross(u,v)
            visible=np.dot(normal,camera_normal)>-.02
            opacity=1 if visible else 0
            corners=np.array([c-.5*u-.5*v,c+.5*u-.5*v,c+.5*u+.5*v,c-.5*u+.5*v])
            color=self.p['accent'] if name=='E' else self.p['second'] if name=='D' else self.p['panel']
            color=interpolate_color(ManimColor(self.p['bg']),ManimColor(color),.36).to_hex() if name in ('E','D') else color
            fill=1
            shape=Polygon(*project(corners),fill_color=color,fill_opacity=fill*opacity,stroke_color=self.p['fg'] if self.scene.lesson_style.get('template_id')=='studio_sketch' else self.p['line'],stroke_width=2.1,stroke_opacity=opacity)
            label=self.labels[name].copy()
            # Affine projection keeps letters and their orientation attached to each face.
            label.apply_function(lambda pt,c=c,u=u,v=v: project([c+pt[0]*u+pt[1]*v])[0])
            label.set_opacity(opacity)
            mark=Dot(project([c+.34*u+.34*v])[0],radius=.035*self.unit,color=self.p['fg']).set_opacity(opacity)
            group=VGroup(shape,label,mark)
            rough_file=Path(__file__).with_name('rough_square.json')
            if self.scene.lesson_style.get('template_id')=='studio_sketch' and rough_file.is_file():
                for operations in json.loads(rough_file.read_text())['paths']:
                    stroke=VMobject(stroke_color=self.p['fg'],stroke_width=1.7,stroke_opacity=opacity)
                    for op in operations:
                        d=op['data']
                        pts=project([c+(d[i]/100)*u+(d[i+1]/100)*v for i in range(0,len(d),2)])
                        if op['op']=='move':stroke.start_new_path(pts[0])
                        elif op['op']=='bcurveTo':stroke.add_cubic_bezier_curve_to(*pts)
                        elif op['op']=='lineTo':stroke.add_line_to(pts[0])
                    group.add(stroke)
            self.faces[name].become(group)
            records.append((np.dot(c,camera_normal),self.faces[name]))
        for depth,group in records:group.set_z_index(1+depth)
        self.highlight_lines.become(VGroup())
        if self.highlight:
            # Material top of D becomes the bottom edge of its transferred square.
            dside='bottom' if self.alternate else 'top'
            for name,side,color in [('E','top',self.p['accent']),('D',dside,self.p['second'])]:
                points=project(edge(f[name],side))
                segment=Line(*points,stroke_color=color,stroke_width=9 if name=='E' else 4).set_z_index(8)
                self.highlight_lines.add(segment,*[Dot(point,radius=(.065 if name=='E' else .04)*self.unit,color=color).set_z_index(9) for point in points])
        return self

def mini_net(scene,cells,center,unit=.27):
    xs=[x for x,y in cells];ys=[y for x,y in cells];offset=np.array([(min(xs)+max(xs))/2,(min(ys)+max(ys))/2,0])
    p=tokens(scene); result=VGroup()
    for x,y in cells:
        pos=(np.array([x,y,0])-offset)*unit+np.array(center)
        square=Square(side_length=unit*.92,fill_color=p['accent'],fill_opacity=.22,stroke_color=p['accent'],stroke_width=1.4).move_to(pos)
        result.add(square)
    return result

def cube_lesson(scene,stage):
    stage=int(stage)
    if stage not in range(6):raise ValueError('cube_lesson stage must be 0..5')
    p=tokens(scene)
    labels=['六面体展开图','11 种展开图 · 4 类结构','只解这一题','沿真实棱折叠','旋转移面 · 方向跟着转','回到原图，选 A']
    chrome(scene,stage,labels[stage])
    if stage==0:
        heading=text(scene,'公共边，\n不用靠想象。',54,point=[-3.5,.75,0])
        sub=text(scene,'认形态  /  追踪边  /  旋转移面',23,p['muted'],[-3.5,-1.15,0])
        badge=text(scene,'公务员考试 · 图形推理',19,p['accent'],[-3.7,2.15,0])
        view=CubeView(scene,scale=1.4,center=[2.3,.1,0],highlight=True)
        scene.play(FadeIn(heading,shift=UP*.15),FadeIn(sub),FadeIn(badge),FadeIn(view),run_time=.55)
        scene.play(UpdateFromAlphaFunc(view,lambda m,a:m.update_pose(a)),run_time=min(2.2,scene.remaining()*.75),rate_func=smooth)
    elif stage==1:
        groups=classified_nets();xs=[-4.7,-1.55,1.55,4.7]
        cards=VGroup()
        for x,(key,nets) in zip(xs,groups.items()):
            card=panel(scene,2.88,4.7,[x,0,0])
            title=text(scene,'—'.join(key),38,p['accent'],[x,1.85,0])
            count=text(scene,f'{len(nets)} 种',21,p['muted'],[x,1.22,0])
            diagrams=VGroup()
            for i,cells in enumerate(nets):
                cols=2 if len(nets)>3 else 1
                xx=x+((i%cols)-.5)*1.2 if cols==2 else x
                yy=.42-(i//cols)*.98 if len(nets)>3 else .4-i*.9 if len(nets)==3 else -.2
                unit=.25 if len(nets)>3 else .245 if len(nets)==3 else .42
                diagrams.add(mini_net(scene,cells,[xx,yy,0],unit))
            cards.add(VGroup(card,title,count,diagrams))
        scene.play(LaggedStart(*[FadeIn(c,shift=UP*.12) for c in cards],lag_ratio=.12),run_time=.9)
        note=text(scene,'1–3–2 与 2–3–1 为同一类的不同朝向',20,p['muted'],[0,-2.7,0])
        scene.play(FadeIn(note),run_time=.35)
    elif stage==2:
        view=CubeView(scene,scale=1.25,center=[-3.05,0,0],highlight=False)
        question=text(scene,'E 与 D 的公共边是？',33,point=[3,1.85,0])
        options=VGroup()
        for i,(letter,side) in enumerate(zip('ABCD',['上边','下边','左边','右边'])):
            center=[3, .85-i*.88,0]
            box=panel(scene,4.7,.7,center)
            content=text(scene,f'{letter}    E 上边 ↔ D {side}',24,point=center)
            options.add(VGroup(box,content))
        scene.play(FadeIn(view),FadeIn(question),LaggedStart(*[FadeIn(o) for o in options],lag_ratio=.1),run_time=.75)
        scene.add(text(scene,'小圆点是方向标记',20,p['muted'],[-2.9,-2.3,0]))
    elif stage==3:
        view=CubeView(scene,scale=1.7,center=[-3,0,0],highlight=True)
        notes=VGroup(text(scene,'固定 B，沿棱折叠',29,point=[3.7,1.15,0]),text(scene,'E 上边',29,p['accent'],[3.7,.3,0]),text(scene,'D 上边',29,p['second'],[3.7,-.4,0]))
        scene.play(FadeIn(view),FadeIn(notes),run_time=.4)
        scene.wait(.2)
        scene.play(UpdateFromAlphaFunc(view,lambda m,a:m.update_pose(a)),run_time=min(2.7,scene.remaining()*.65),rate_func=smooth)
        seam=text(scene,'两条边，折后完全重合',24,p['good'],[2.75,-1.6,0])
        scene.play(FadeIn(seam),run_time=.35)
        scene.add(text(scene,'B 固定',20,p['muted'],[-3,-1.9,0]))
    elif stage==4:
        view=CubeView(scene,TRANSFER,scale=1.7,center=[-3,0,0],fold=1,alternate=True,highlight=True)
        scene.add(view)
        notes=VGroup(text(scene,'把 D 沿公共边重新展开',29,point=[3.7,1.5,0]),text(scene,'面、字母、方向标记\n必须一起旋转',25,p['muted'],[3.6,.25,0]),text(scene,'原来 D 的上边\n现在朝下',27,p['second'],[3.55,-1.3,0]))
        scene.play(FadeIn(notes),run_time=.4)
        def reopen(m,a):
            m.unit=1.7+(1.17-1.7)*a
            m.center_point=np.array([-3+1.8*a,-.35*a,0])
            m.update_pose(1-a)
        scene.play(UpdateFromAlphaFunc(view,reopen),run_time=min(2.6,scene.remaining()*.65),rate_func=smooth)
        arc=Arc(radius=.47,start_angle=-.1,angle=1.65*np.pi,stroke_color=p['second'],stroke_width=3).add_tip(tip_length=.12).move_to([-.2,1.9,0])
        scene.play(Create(arc),FadeIn(text(scene,'180°',24,p['second'],[.85,2.15,0])),run_time=.55)
    else:
        original=CubeView(scene,scale=.98,center=[-3.7,0,0],highlight=True)
        moved=CubeView(scene,TRANSFER,scale=.85,center=[.35,-.2,0],alternate=True,highlight=True)
        scene.add(original,moved)
        scene.add(text(scene,'原展开图',23,p['muted'],[-3.2,-2,0]),text(scene,'移面后',23,p['muted'],[.35,-2,0]))
        answer=VGroup(panel(scene,3.9,2.6,[4.1,.2,0]),text(scene,'答案  A',43,p['good'],[4.1,.8,0]),text(scene,'E 上边 = D 上边',26,point=[4.1,-.1,0]),text(scene,'始终按原图描述边',20,p['muted'],[4.1,-.7,0]))
        scene.play(FadeIn(answer,shift=UP*.1),run_time=.6)
        scene.add(text(scene,'记住：移面可以换位置，边的身份不会变。',23,p['accent'],[0,-2.65,0]))
    return None

def studio(scene,kind,title='',items=None):
    """Reusable layout component for arbitrary topics, used by the normal coder."""
    items=items or []
    if kind=='comparison':
        if len(items)!=2:raise ValueError('comparison requires two items')
        group=VGroup(*[VGroup(panel(scene,5.5,3.8,[x,0,0]),text(scene,str(item),30,point=[x,0,0])) for x,item in zip([-3,3],items)])
    elif kind=='steps':
        if not 1<=len(items)<=4:raise ValueError('steps requires 1..4 items')
        group=VGroup()
        for i,item in enumerate(items):
            x=(i-(len(items)-1)/2)*3
            group.add(VGroup(Circle(radius=.4,color=tokens(scene)['accent']).move_to([x,.7,0]),text(scene,str(i+1),27,point=[x,.7,0]),text(scene,str(item),25,point=[x,-.4,0])))
    else:raise ValueError('Unknown studio component')
    scene.play(LaggedStart(*[FadeIn(m,shift=UP*.12) for m in group],lag_ratio=.15),run_time=.8)
    return group
